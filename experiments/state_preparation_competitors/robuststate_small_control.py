"""Run a paper-sized RobustState control without changing its training algorithm."""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import platform
from pathlib import Path
from typing import TYPE_CHECKING, Any

import numpy as np

from benchmarks.generate_state_preparation_targets import generate_target_records, json_vector_to_state
from experiments.state_preparation_competitors import robuststate
from experiments.state_preparation_competitors.logical_evaluation import score_exact
from experiments.state_preparation_competitors.noisy_core import DenseObjective
from experiments.state_preparation_competitors.run import save_bundle, write_json

if TYPE_CHECKING:
    from collections.abc import Sequence

TARGETS = ("haar_random_1", "gaussian_mu0p5_sigma0p1")


def run_case(
    output: Path,
    target_id: str,
    seed: int,
    *,
    noiseless_steps: int = 500,
    noisy_steps: int = 50,
) -> dict[str, Any]:
    """Compare full-basis sampled training with a matched exact-feedback control.

    Args:
        output: New directory for the protocol and authenticated compact bundle.
        target_id: Four-qubit Haar or Gaussian target generated by existing code.
        seed: Fixed root seed for initialization and measurements.
        noiseless_steps: Published default 500; overrides are only for tests.
        noisy_steps: Published default 50; overrides are only for tests.

    Returns:
        Small summary referencing histories stored once in the sealed bundle.

    Raises:
        ValueError: If the target is unsupported or the destination already exists.
    """
    if target_id not in TARGETS or output.exists():
        msg = "Require a supported control target and a new output directory."
        raise ValueError(msg)
    target_record: dict[str, Any] = next(row for row in generate_target_records((4,)) if row["target_id"] == target_id)
    target = json_vector_to_state(target_record["state_vector"])
    circuit = robuststate.topology_aware_ansatz(4, 4)
    engine = DenseObjective(circuit, target, "IBM", compile_native=False)
    initialization_seed, measurement_seed = map(int, np.random.SeedSequence([seed, 4]).generate_state(2))
    initial = np.random.default_rng(initialization_seed).uniform(-np.pi, np.pi, circuit.num_parameters)
    sources = [Path(robuststate.__file__), Path(__file__)]
    sources += [
        Path("experiments/state_preparation_competitors") / name
        for name in (
            "noisy_core.py",
            "logical_evaluation.py",
            "evaluation.py",
            "run.py",
            "histories.py",
        )
    ]
    sources += [
        Path("benchmarks/generate_state_preparation_targets.py"),
        Path("experiments/state_preparation_exact_adam.py"),
    ]
    manifest = {
        "schema": "yaqs.robuststate_small_control.v1",
        "target": target_record,
        "target_sha256": hashlib.sha256(target.tobytes()).hexdigest(),
        "seed": seed,
        "initialization_seed": initialization_seed,
        "measurement_seed": measurement_seed,
        "num_qubits": 4,
        "depth": 4,
        "cnot_blocks": 12,
        "parameters": circuit.num_parameters,
        "noiseless_steps": noiseless_steps,
        "noisy_steps": noisy_steps,
        "learning_rate": 0.005,
        "bases": 81,
        "shots_per_basis": 1024,
        "hardware": "IBM",
        "noise_basis": "logical",
        "feedback_arms": ["exact_density", "pauli_shadows"],
        "selection": "none; retain final iterate of every prespecified run",
        "source_sha256": {str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in sources},
        "python": platform.python_version(),
        "versions": {name: importlib.metadata.version(name) for name in ("numpy", "scipy", "qiskit")},
    }
    write_json(output / "manifest.json", manifest)
    print(f"Starting {target_id}, seed {seed}", flush=True)
    arms, circuits = {}, []
    warm_history = None
    for feedback in manifest["feedback_arms"]:
        theta, training = robuststate.train_robuststate(
            engine,
            initial,
            seed=measurement_seed,
            noiseless_steps=noiseless_steps,
            noisy_steps=noisy_steps,
            feedback=feedback,
            num_bases=81,
            shots_per_basis=1024,
        )
        history = np.array([row["theta"] for row in training["records"]])
        if warm_history is None:
            warm_history = history[: noiseless_steps + 1].copy()
            warm_circuit = engine.bind(warm_history[-1])
            circuits.append(warm_circuit)
            before = score_exact(warm_circuit, target, "IBM")
            ideal = engine.ideal_density(warm_history[-1])
            ideal_fidelity = float(np.vdot(target, ideal @ target).real)
        else:
            np.testing.assert_array_equal(history[: noiseless_steps + 1], warm_history)
        final_circuit = engine.bind(theta)
        final = score_exact(final_circuit, target, "IBM")
        np.testing.assert_allclose(final["fidelity"], training["records"][-1]["fidelity"], atol=1e-12, rtol=0)
        circuits.append(final_circuit)
        arms[feedback] = {"training": training, "final_score": final, "circuit_index": len(circuits) - 1}
        print(f"Completed {target_id}, seed {seed}, {feedback}: F={final['fidelity']:.9f}", flush=True)
    summary = {
        "target_id": target_id,
        "seed": seed,
        "warm_ideal_fidelity": ideal_fidelity,
        "warm_noisy_fidelity": before["fidelity"],
        "matched_warm_parameters": True,
        "warm_ideal_above_99_percent": ideal_fidelity >= 0.99,
        "arms": {
            name: {
                "final_noisy_fidelity": arm["final_score"]["fidelity"],
                "change_percentage_points": 100 * (arm["final_score"]["fidelity"] - before["fidelity"]),
                "wall_seconds": arm["training"]["wall_seconds"],
                "cpu_seconds": arm["training"]["cpu_seconds"],
                "shots": arm["training"]["total_shots"],
            }
            for name, arm in arms.items()
        },
        "bundle": "bundle",
        "warm_circuit_index": 0,
    }
    save_bundle(output / "bundle", {"summary": summary, "arms": arms}, circuits)
    write_json(output / "summary.json", summary)
    return summary


def main(argv: Sequence[str] | None = None) -> None:
    """Run one bounded four-qubit control pair from the command line."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--target-id", choices=TARGETS, required=True)
    parser.add_argument("--seed", type=int, required=True)
    args = parser.parse_args(argv)
    run_case(args.output, args.target_id, args.seed)


if __name__ == "__main__":
    main()
